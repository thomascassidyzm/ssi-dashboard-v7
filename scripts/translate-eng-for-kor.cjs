async function patchSeed(seed, known_text, target_text) {
  const body = {};
  if (known_text) body.known_text = known_text;
  if (target_text) body.target_text = target_text;

  const res = await fetch(`http://localhost:3471/api/seed/eng_for_kor/${seed}`, {
    method: 'PATCH',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });

  if (!res.ok) {
    const text = await res.text();
    console.error(`✗ Seed ${seed}: ${res.status} - ${text}`);
    return false;
  }
  return true;
}

async function main() {
  console.log(`Translating ${translations.length} seeds for eng_for_kor...`);

  let success = 0;
  let failed = 0;

  // Process in batches of 10 to avoid overwhelming the server
  const batchSize = 10;
  for (let i = 0; i < translations.length; i += batchSize) {
    const batch = translations.slice(i, i + batchSize);
    const promises = batch.map(t => patchSeed(t.seed, t.known, t.target));
    const results = await Promise.all(promises);

    results.forEach((ok, j) => {
      const t = batch[j];
      if (ok) {
        success++;
        if (success % 50 === 0) console.log(`  ✓ ${success} seeds translated...`);
      } else {
        failed++;
      }
    });
  }

  console.log(`\nDone: ${success} succeeded, ${failed} failed out of ${translations.length} total.`);
}

main().catch(console.error);
