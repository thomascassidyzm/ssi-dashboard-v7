#!/usr/bin/env node
/**
 * ESTATE-WIDE POD-1 PER-CONVERSATION RECAST (2026-08-23).
 *
 * Generalisation of tools/pods/cym-n-pod0-percall-recast.cjs from one Welsh pod
 * to every course's serving pod. Tom's ruling, verbatim:
 *
 *   "I think the talking to yourself might have happened because of the desire
 *    to cast just 2 voices. But it shouldn't have. It should be male/female
 *    every conversation."
 *
 * Settled and not re-opened here: cast PER CONVERSATION (a label may be male in
 * one scene and female in another); TWO voices only; ZERO same-voice exchanges
 * with no soft bucket; a character voiced against apparent gender is an
 * ACCEPTED COST; no script rewrites; nothing deleted or unlinked (make before
 * break); NO TTS is generated by this tool, ever.
 *
 * ── What it writes ────────────────────────────────────────────────────────────
 *   listening_pod_sentences.speaker   scene-unique relabels, scenes 7/8/9 only
 *   listening_pods.speakers           the render/serving cast for a TTS pod
 *   courses.voice_config.podCast      the HUMAN recording cast (kept in step)
 * Never touched: target_text, known_text, target_audio_id, known_audio_id,
 * voice_config.voices (asserted byte-identical before commit).
 *
 * ── Why relabelling is the mechanism ──────────────────────────────────────────
 * Both cast stores are keyed by CANONICAL speaker name alone, and
 * canonicalSpeakerName() strips parenthesised groups — so a bracketed scene
 * suffix cannot express a scene-scoped cast. The fix is therefore to make the
 * reused LABELS themselves scene-unique (Cafe Customer 1 / Bar Customer 1 /
 * Diner 1) and write one cast entry per scene-unique label. This is safe under
 * the content-change migration protocol because learner progress is filed under
 * the SLOT id `${podId}:SC{scene}-S{sentence}` — a speaker relabel does not
 * move a slot, so nobody is mis-credited and no migration is owed.
 *
 * ── The edge definition (where we differ from #129, deliberately) ─────────────
 * buildTurnWeights() counts every pair of CONSECUTIVE speaker labels as an
 * exchange. In the cafe/bar/restaurant scenes the customers never address each
 * other — they each address the staff — so Customer 1 followed by Customer 2 is
 * two orders at a shared hub, not a conversation. Aran, who reads the lines,
 * disputed #129 on exactly this ground and the line text bore him out. The
 * pairs are enumerated in NON_EXCHANGE below so the judgement is auditable.
 * The estate ships ONE English script for this pod: scenes 7/8/9 are word-for-
 * word identical across every structural class (verified 2026-08-23 across the
 * 142/231/232-row classes and the eng_for_* courses, where the same lines are
 * the TARGET text), so the Welsh adjudication transfers verbatim.
 *
 * Usage:
 *   node tools/pods/pod1-percall-recast.cjs --pod=<podId>            # dry run
 *   node tools/pods/pod1-percall-recast.cjs --pod=<podId> --apply    # write
 *   node tools/pods/pod1-percall-recast.cjs --all                    # dry-run sweep
 */

