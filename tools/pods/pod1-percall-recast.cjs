async function recastPod(db, podId) {
  const pod = (await db.query(
    `select id, course_code, slug, visibility, speakers from listening_pods where id = $1`, [podId])).rows[0]
  if (!pod) throw new Error(`pod ${podId} not found`)

  const rows = (await db.query(
    `select id, pod_id, scene_number, sentence_number, global_order, speaker,
            known_text, glue_to_next, target_audio_id, known_audio_id
       from listening_pod_sentences where pod_id = $1
      order by global_order, scene_number, sentence_number`, [podId])).rows

  // Glued rows are chained by RAW speaker-string equality in the player
  // (usePodLapScheduler.ts), so a relabel that splits a glued chain would
  // break it. Refuse rather than write through it.
  const glued = rows.filter(r => r.glue_to_next)

  const course = (await db.query(
    `select course_code, voice_config from courses where course_code = $1`, [pod.course_code])).rows[0]

  // Delivered voice per line — the only honest measure of what a learner hears.
  const audioIds = [...new Set(rows.flatMap(r => [r.target_audio_id, r.known_audio_id]).filter(Boolean))]
  const audio = new Map()
  if (audioIds.length) {
    const res = await db.query(`select id, voice_id from course_audio where id = any($1::uuid[])`, [audioIds])
    for (const a of res.rows) audio.set(a.id, norm(a.voice_id))
  }
  const deliveredTarget = (r) => (r.target_audio_id ? audio.get(r.target_audio_id) : null) || null
  const deliveredKnown = (r) => (r.known_audio_id ? audio.get(r.known_audio_id) : null) || null

  const storedCast = pod.speakers || {}

  // ---- voice → gender ------------------------------------------------------
  // Primary source: the stored cast's own per-speaker gender (this is the
  // estate's live belief and what currently ships). Cross-check against the
  // `voices` table where it has a non-null value; a conflict is reported, not
  // silently resolved.
  const voiceGenderVotes = new Map() // normalised voice id -> {f,m}
  const vote = (vid, g) => {
    if (!vid || (g !== 'f' && g !== 'm')) return
    if (!voiceGenderVotes.has(vid)) voiceGenderVotes.set(vid, { f: 0, m: 0 })
    voiceGenderVotes.get(vid)[g] += 1
  }
  for (const [, entry] of Object.entries(storedCast)) {
    if (!entry) continue
    vote(norm(entry.target && entry.target.voice_id), entry.gender)
    vote(norm(entry.known && entry.known.voice_id), entry.gender)
  }
  const allVoiceIds = [...new Set([
    ...rows.map(deliveredTarget), ...rows.map(deliveredKnown),
    ...Object.values(storedCast).flatMap(e => e ? [norm(e.target && e.target.voice_id), norm(e.known && e.known.voice_id)] : []),
  ].filter(Boolean))]
  const voicesRow = allVoiceIds.length
    ? (await db.query(
        `select voice_id, display_name, gender, tts_engine, tts_locale from voices
          where regexp_replace(voice_id,'^(xai_|azure_)','') = any($1::text[])`, [allVoiceIds])).rows
    : []
  const tableGender = new Map(voicesRow.filter(v => v.gender === 'f' || v.gender === 'm').map(v => [norm(v.voice_id), v.gender]))
  const voiceMeta = new Map(voicesRow.map(v => [norm(v.voice_id), v]))

  const genderConflicts = []
  const voiceGender = new Map()
  for (const vid of allVoiceIds) {
    const votes = voiceGenderVotes.get(vid)
    const cast = votes ? (votes.f > votes.m ? 'f' : votes.m > votes.f ? 'm' : null) : null
    const tab = tableGender.get(vid) || null
    if (cast && tab && cast !== tab) genderConflicts.push({ voice: vid, storedCast: cast, voicesTable: tab, votes })
    const g = tab || cast
    if (g) voiceGender.set(vid, g)
  }

  // ---- pick the two voices per track ---------------------------------------
  // Taste-safe default: where a track currently uses more than two voices, keep
  // the male and the female with the most delivered DISTINCT CLIPS. Ranking by
  // rows would over-value a voice whose few clips are reused across many slots,
  // and the clip is what phase 8 re-renders. Discards reported.
  function pickPair(deliveredOf, audioIdOf) {
    const clipsPerVoice = new Map()
    const linesPerVoice = new Map()
    for (const r of rows) {
      const v = deliveredOf(r), id = audioIdOf(r)
      if (!v || !id) continue
      if (!clipsPerVoice.has(v)) clipsPerVoice.set(v, new Set())
      clipsPerVoice.get(v).add(id)
      linesPerVoice.set(v, (linesPerVoice.get(v) || 0) + 1)
    }
    const counts = new Map([...clipsPerVoice.entries()].map(([v, s]) => [v, s.size]))
    if (!counts.size) {
      // No delivered audio: fall back to the stored cast's own voices.
      for (const e of Object.values(storedCast)) {
        const v = norm(deliveredOf === deliveredTarget
          ? (e && e.target && e.target.voice_id) : (e && e.known && e.known.voice_id))
        if (v) counts.set(v, (counts.get(v) || 0) + 1)
      }
    }
    const ranked = [...counts.entries()].sort((a, b) => b[1] - a[1])
    const f = ranked.find(([v]) => voiceGender.get(v) === 'f')
    const m = ranked.find(([v]) => voiceGender.get(v) === 'm')
    const ungendered = ranked.filter(([v]) => !voiceGender.has(v))
    const discarded = ranked.filter(([v]) => v !== (f && f[0]) && v !== (m && m[0]))
    return {
      f: f ? f[0] : null, m: m ? m[0] : null,
      single: ranked.length ? ranked[0][0] : null,
      counts: Object.fromEntries(ranked), // DISTINCT CLIPS per voice
      countsByLine: Object.fromEntries([...linesPerVoice.entries()].sort((a, b) => b[1] - a[1])),
      discarded, ungendered,
      distinct: ranked.length,
    }
  }
  const tgtPair = pickPair(deliveredTarget, (r) => r.target_audio_id)
  const knwPair = pickPair(deliveredKnown, (r) => r.known_audio_id)
  /**
   * Does the known track have a gender split to make at all? The eng_for_*
   * shape is one target-language narrator reading every character's known
   * line — there are no known-side exchanges to fix, so this job has no
   * business touching that track. When there is no resolvable f/m pair the
   * known cast entry is carried across from the stored cast UNCHANGED, per
   * speaker. That matters: pod-recast.cjs corrected 16 eng_for_* known casts
   * forward on 2026-08-07, and rewriting them from the shipped audio would
   * silently revert somebody else's fix over a question this ruling never
   * asked.
   */
  const knownTrackInScope = !!(knwPair.f && knwPair.m)

  // ---- graph ---------------------------------------------------------------
  const oldName = (r) => canonicalSpeakerName(r.speaker)
  const newName = sceneUniqueName
  const allNew = [...new Set(rows.map(newName))]
  const variantsOf = new Map()
  for (const r of rows) {
    const n = newName(r)
    if (!variantsOf.has(n)) variantsOf.set(n, new Set())
    variantsOf.get(n).add(r.speaker)
  }

  const { weights: exWeights, dropped } = buildExchangeWeights(rows, newName)
  const { colour, components, oddCycle } = twoColour(exWeights, allNew)

  // ---- orient each component to KEEP THE AUDIO THAT ALREADY EXISTS ---------
  // Both orientations of a component are equally collision-free, so the choice
  // is free of the hard rule and is spent on the delivered clips instead.
  // Orientation is PER COMPONENT: each one chooses independently.
  const orientClips = []
  for (const r of rows) {
    const n = newName(r)
    for (const track of ['target', 'known']) {
      const audioId = track === 'target' ? r.target_audio_id : r.known_audio_id
      const delivered = track === 'target' ? deliveredTarget(r) : deliveredKnown(r)
      if (!audioId || !delivered) continue
      // The out-of-scope known track is carried across untouched, so its clips
      // cannot be moved by an orientation and must not vote on one.
      const wantF = track === 'target' ? tgtPair.f : (knownTrackInScope ? knwPair.f : null)
      const wantM = track === 'target' ? tgtPair.m : (knownTrackInScope ? knwPair.m : null)
      if (!wantF || !wantM) continue
      orientClips.push({ name: n, track, audioId, voice: delivered, wantF, wantM })
    }
  }
  const orientation = []
  for (const comp of components) {
    const d = orientComponent({
      members: comp,
      colourOf: (n) => colour.get(n),
      clips: orientClips,
      scriptGenderOf: (n) => scriptGender(n, variantsOf.get(n)),
    })
    if (d.flip) for (const n of comp) colour.set(n, 1 - colour.get(n))
    orientation.push({ size: comp.length, flipped: d.flip, decidedBy: d.decidedBy,
      deliveredClipsKept: d.deliveredClipsKept, scriptGenderScore: d.scriptGenderScore,
      clipsInComponent: d.clipsInComponent,
      scriptFixedNames: d.scriptFixedNames, members: comp })
  }
  const genderOf = (n) => (colour.get(n) === 0 ? 'f' : 'm')
  const forcedMismatch = allNew
    .map(n => ({ name: n, script: scriptGender(n, variantsOf.get(n)), cast: genderOf(n) }))
    .filter(x => x.script && x.script !== x.cast)

  // ---- metrics -------------------------------------------------------------
  const oldTargetVoiceOf = (r) => deliveredTarget(r)
  const oldCollisions = (() => {
    // Baseline measured on the DELIVERED voice, per consecutive pair.
    let pairs = new Set(), turns = 0, exPairs = new Set(), exTurns = 0
    for (let i = 1; i < rows.length; i++) {
      const p = rows[i - 1], c = rows[i]
      if (p.scene_number !== c.scene_number) continue
      const a = oldName(p), b = oldName(c)
      if (a === b) continue
      const va = oldTargetVoiceOf(p), vb = oldTargetVoiceOf(c)
      if (!va || !vb || va !== vb) continue
      const tag = `${p.scene_number}:${p.sentence_number}->${c.scene_number}:${c.sentence_number}`
      const key = a < b ? `${a}|${b}` : `${b}|${a}`
      pairs.add(key); turns++
      if (!NON_EXCHANGE.has(tag)) { exPairs.add(key); exTurns++ }
    }
    return { rawPairs: pairs.size, rawTurns: turns, exchangePairs: exPairs.size, exchangeTurns: exTurns }
  })()

  const newVoiceTarget = (n) => (genderOf(n) === 'f' ? tgtPair.f : tgtPair.m)
  const newVoiceKnown = (n) => {
    if (!knownTrackInScope) return null
    return genderOf(n) === 'f' ? knwPair.f : knwPair.m
  }
  const proposedExchange = countAdjacentCollisions(exWeights, newVoiceTarget)
  const proposedRaw = countAdjacentCollisions(buildTurnWeights(sceneLists(rows, newName)), newVoiceTarget)

  const residue = []
  for (let i = 1; i < rows.length; i++) {
    const p = rows[i - 1], c = rows[i]
    if (p.scene_number !== c.scene_number) continue
    const a = newName(p), b = newName(c)
    if (a === b) continue
    if (newVoiceTarget(a) && newVoiceTarget(a) === newVoiceTarget(b)) {
      const tag = `${p.scene_number}:${p.sentence_number}->${c.scene_number}:${c.sentence_number}`
      residue.push({ tag, a, b, voice: newVoiceTarget(a), exchange: !NON_EXCHANGE.has(tag) })
    }
  }

  // ---- row plans -----------------------------------------------------------
  const relabels = []
  for (const r of rows) {
    const to = newName(r)
    if (r.speaker !== to && canonicalSpeakerName(r.speaker) !== to) {
      relabels.push({ id: r.id, scene: r.scene_number, sentence: r.sentence_number, from: r.speaker, to })
    }
  }
  const gluedInRelabel = glued.filter(g => relabels.some(r => r.id === g.id))

  // The regen queue holds every line whose EXISTING CLIP is now in the wrong
  // voice — delivered voice ≠ the voice the new cast names. Nothing here is
  // re-rendered, unlinked or deleted: the old clip keeps serving until a
  // verified replacement exists (make before break).
  //
  // `causedByRecast` separates the two reasons a line can be in the queue:
  //   true  — this recast moved the character to the other voice;
  //   false — the clip already disagreed with the pod's OWN stored cast before
  //           this job ran (pre-existing drift, e.g. audio rendered before
  //           pod-recast.cjs corrected the cast on 2026-08-07). Counting that
  //           as this job's burden would inflate the number Tom is waiting for.
  //
  // The comparison is against the ORIGINAL (pre-recast) cast wherever the first
  // pass's log records it — see loadBaselineCast(). On a second pass the pod's
  // stored cast is already a recast cast, so it is no longer a baseline.
  const oldCastVoice = (r, track) => {
    const e = storedCast[canonicalSpeakerName(r.speaker)] || storedCast._default
    const t = e && (track === 'target' ? e.target : e.known)
    return t ? norm(t.voice_id) : null
  }
  const baseline = loadBaselineCast()
  let baselineHits = 0
  const regenQueue = []
  for (const r of rows) {
    const n = newName(r)
    for (const track of ['target', 'known']) {
      const delivered = track === 'target' ? deliveredTarget(r) : deliveredKnown(r)
      const next = track === 'target' ? newVoiceTarget(n) : newVoiceKnown(n)
      if (!delivered || !next || delivered === next) continue
      const fromBaseline = baseline.get(`${podId}|${r.scene_number}|${r.sentence_number}|${track}`) || null
      if (fromBaseline) baselineHits++
      const prevCast = fromBaseline || oldCastVoice(r, track)
      // Pre-existing drift = the clip already disagreed with its OWN cast before
      // any recast ran. Everything else queued is this recast's burden.
      const drift = !!prevCast && prevCast !== delivered
      regenQueue.push({ course: pod.course_code, pod: podId, global_order: r.global_order,
        scene: r.scene_number, sentence: r.sentence_number, track,
        clipId: track === 'target' ? r.target_audio_id : r.known_audio_id,
        speakerBefore: r.speaker, speakerAfter: n,
        voiceBefore: delivered, voiceAfter: next, castVoiceBefore: prevCast,
        castVoiceBeforeSource: fromBaseline ? 'pre-recast-baseline' : 'stored-cast',
        causedByRecast: !drift })
    }
  }
  const causedByRecast = regenQueue.filter(q => q.causedByRecast)
  const preexistingDrift = regenQueue.filter(q => !q.causedByRecast)

  // ---- the new stored cast -------------------------------------------------
  // A cast entry reproduces the voice EXACTLY as the pod already spells it
  // where the stored cast already names that voice; otherwise it is rebuilt
  // from the `voices` table so provider/locale reach the render path. The
  // voice written is the one ACTUALLY SERVING today (from course_audio), so
  // this also stops a stored cast that has drifted from its own audio lying.
  const templateFor = (vid, track) => {
    for (const e of Object.values(storedCast)) {
      if (!e) continue
      const t = track === 'target' ? e.target : e.known
      if (t && norm(t.voice_id) === vid) return { ...t }
    }
    const v = voiceMeta.get(vid)
    if (!v) return { voice_id: vid, name: vid }
    return {
      name: v.display_name || vid,
      ...(v.tts_locale ? { locale: v.tts_locale } : {}),
      ...(v.tts_engine ? { provider: v.tts_engine } : {}),
      voice_id: vid,
    }
  }
  // Out-of-scope known track: carry each speaker's stored known entry across
  // untouched, matched on the speaker's PRE-relabel canonical name.
  const storedKnownFor = (newLabel) => {
    if (knownTrackInScope) return null
    const row = rows.find(r => newName(r) === newLabel)
    const e = (row && storedCast[canonicalSpeakerName(row.speaker)]) || storedCast._default
    return e && e.known ? { ...e.known } : null
  }
  const newSpeakers = {}
  for (const n of allNew) {
    const g = genderOf(n)
    const t = newVoiceTarget(n), k = newVoiceKnown(n)
    newSpeakers[n] = {
      gender: g,
      variants: [...variantsOf.get(n)].map(v => (RELABEL[0] ? v : v)).filter(Boolean),
      ...(t ? { target: templateFor(t, 'target') } : {}),
      ...(k ? { known: templateFor(k, 'known') } : storedKnownFor(n) ? { known: storedKnownFor(n) } : {}),
    }
    // After relabelling, the row's own speaker string IS the scene-unique name.
    newSpeakers[n].variants = [...new Set(rows.filter(r => newName(r) === n).map(r => (relabels.some(x => x.id === r.id) ? n : r.speaker)))]
  }

  // Human recording cast, kept in step with the render cast.
  const oldPodCast = (course.voice_config && course.voice_config.podCast) || {}

  const blockers = []
  if (!tgtPair.f || !tgtPair.m) {
    blockers.push(`target track has no resolvable ${!tgtPair.f ? 'female' : 'male'} voice ` +
      `(voices seen: ${JSON.stringify(tgtPair.counts)}; ungendered: ${tgtPair.ungendered.map(u => u[0]).join(',') || 'none'})`)
  }
  if (oddCycle) blockers.push(`exchange graph is NOT bipartite: ${oddCycle.a} — ${oddCycle.b}; two voices cannot reach zero without a script rewrite`)
  if (gluedInRelabel.length) blockers.push(`${gluedInRelabel.length} glued rows fall inside the relabel set — the player chains glue by raw speaker string`)
  // The hard rule, asserted rather than assumed. Cost-aware orientation cannot
  // reach it (both orientations are collision-free) but nothing here trusts that.
  if (proposedExchange.pairs || proposedExchange.turns) {
    blockers.push(`proposed cast leaves ${proposedExchange.pairs} same-voice exchange pair(s) / ${proposedExchange.turns} turn(s) — the zero rule is non-negotiable`)
  }

  const report = {
    pod: podId, course: pod.course_code, slug: pod.slug, visibility: pod.visibility,
    mode: APPLY ? 'applied' : 'dryrun', rows: rows.length,
    linkedTarget: rows.filter(r => r.target_audio_id).length,
    linkedKnown: rows.filter(r => r.known_audio_id).length,
    gluedRows: glued.length,
    voicePairTarget: tgtPair, voicePairKnown: knwPair, knownTrackInScope,
    voiceGender: Object.fromEntries(voiceGender), genderConflicts,
    baselineDeliveredCollisions: oldCollisions,
    proposedExchangeCollisions: proposedExchange,
    proposedRawLabelCollisions: proposedRaw,
    nonExchangePairsDropped: dropped,
    sameVoiceConsecutiveResidue: residue,
    componentsOriented: orientation,
    forcedGenderMismatch: forcedMismatch,
    relabelCount: relabels.length, relabels,
    regenLines: regenQueue.length,
    regenLinesTarget: regenQueue.filter(q => q.track === 'target').length,
    regenLinesKnown: regenQueue.filter(q => q.track === 'known').length,
    regenCausedByThisRecast: causedByRecast.length,
    regenPreexistingDrift: preexistingDrift.length,
    regenAttributionFromBaseline: baselineHits,
    // Distinct clips, not line-links: the unit phase 8 re-renders.
    regenDistinctClips: new Set(regenQueue.map(q => `${q.track}|${q.clipId}`)).size,
    regenDistinctClipsCausedByRecast: new Set(causedByRecast.map(q => `${q.track}|${q.clipId}`)).size,
    deliveredClipsKeptByOrientation: orientation.reduce((n, o) => n + o.deliveredClipsKept.chosen, 0),
    deliveredClipsKeptIfUnflipped: orientation.reduce((n, o) => n + o.deliveredClipsKept.asColoured, 0),
    regenQueue,
    blockers,
    oldStoredCastKeys: Object.keys(storedCast).sort(),
    newStoredCast: newSpeakers,
    oldPodCastKeys: Object.keys(oldPodCast).sort(),
  }

  if (APPLY) {
    if (blockers.length) throw new Error(`REFUSING to apply ${podId}: ${blockers.join(' | ')}`)
    await db.query('begin')
    try {
      for (const rl of relabels) {
        const res = await db.query(
          `update listening_pod_sentences set speaker = $1
            where id = $2 and speaker = $3 and pod_id = $4`, [rl.to, rl.id, rl.from, podId])
        if (res.rowCount !== 1) throw new Error(`before-state assertion failed on ${rl.id}: expected speaker "${rl.from}"`)
      }
      const resPod = await db.query(
        `update listening_pods set speakers = $1 where id = $2`, [newSpeakers, podId])
      if (resPod.rowCount !== 1) throw new Error('pod cast update did not affect exactly 1 row')

      // Human recording cast — mirror the same gender split onto whatever human
      // voices the course already names, if it names any. Never invent voices.
      if (Object.keys(oldPodCast).length) {
        const vc = JSON.parse(JSON.stringify(course.voice_config))
        const byGender = { f: null, m: null }
        for (const [k, e] of Object.entries(oldPodCast)) {
          if (!e || !e.voiceId) continue
          const g = e.gender || (voiceGender.get(norm(e.voiceId)) || null)
          if (g === 'f' || g === 'm') { if (!byGender[g]) byGender[g] = e }
          void k
        }
        if (byGender.f && byGender.m) {
          const next = {}
          for (const n of allNew) next[n] = { ...byGender[genderOf(n)] }
          if (oldPodCast.__explainer__) next.__explainer__ = { ...oldPodCast.__explainer__ }
          vc.podCast = next
          if (JSON.stringify(vc.voices || null) !== JSON.stringify(course.voice_config.voices || null)) {
            throw new Error('voice_config.voices changed — aborting')
          }
          const r2 = await db.query(`update courses set voice_config = $1 where course_code = $2`, [vc, pod.course_code])
          if (r2.rowCount !== 1) throw new Error('course update did not affect exactly 1 row')
          report.appliedPodCast = next
        } else {
          report.podCastSkipped = 'existing podCast does not name one female and one male voice — left untouched'
        }
      } else {
        report.podCastSkipped = 'course has no podCast — nothing to keep in step'
      }
      await db.query('commit')
    } catch (e) { await db.query('rollback'); throw e }

    // Re-derive from the live DB after the write.
    const after = (await db.query(
      `select id, scene_number, sentence_number, global_order, speaker, known_text,
              target_audio_id, known_audio_id
         from listening_pod_sentences where pod_id = $1
        order by global_order, scene_number, sentence_number`, [podId])).rows
    const liveCast = (await db.query(`select speakers from listening_pods where id = $1`, [podId])).rows[0].speakers
    const liveVoice = (n) => {
      const e = liveCast[canonicalSpeakerName(n)]
      return e && e.target ? norm(e.target.voice_id) : null
    }
    const liveName = (r) => canonicalSpeakerName(r.speaker)
    const { weights: liveEx } = buildExchangeWeights(after, liveName)
    report.verifiedLive = {
      exchangeCollisions: countAdjacentCollisions(liveEx, liveVoice),
      rawLabelCollisions: countAdjacentCollisions(buildTurnWeights(sceneLists(after, liveName)), liveVoice),
      targetLinksIntact: after.filter(r => r.target_audio_id).length,
      knownLinksIntact: after.filter(r => r.known_audio_id).length,
      castKeys: Object.keys(liveCast).sort(),
    }
  }

  return report
}

async function main() {
  require('dotenv').config({ path: path.join(__dirname, '../../.env.psql') })
  const db = new Client({ connectionString: process.env.DATABASE_URL })
  await db.connect()

  let podIds = []
  if (POD_ARG) podIds = [POD_ARG]
  else if (ALL) {
    // cym_n_for_eng is human-voiced by Aran and Catrin and its casting is
    // settled by their live recording queues (jobs #131/#132) — excluded
    // explicitly, not left to the visibility filter that happens to hide it
    // today (both its pods are 'held' as of 2026-08-23).
    podIds = (await db.query(
      `select id from listening_pods
        where visibility = 'live' and slug in ('pod-0','pod-1')
          and course_code not like 'zzz%'
          and course_code <> 'cym_n_for_eng'
        order by id`)).rows.map(r => r.id)
  } else { throw new Error('need --pod=<podId> or --all') }

  const reports = []
  for (const id of podIds) {
    try { reports.push(await recastPod(db, id)) }
    catch (e) { reports.push({ pod: id, mode: APPLY ? 'applied' : 'dryrun', error: String(e.message || e) }) }
  }

  const suffix = APPLY ? 'applied' : 'dryrun'
  const name = POD_ARG ? `pod1-percall-recast-${POD_ARG.replace(/[:]/g, '-')}-${STAMP}-${RUN}-${suffix}-log.json`
                       : `pod1-percall-recast-estate-${STAMP}-${RUN}-${suffix}-log.json`
  const out = path.join(OUT_DIR, name)
  fs.writeFileSync(out, JSON.stringify(reports.length === 1 ? reports[0] : reports, null, 2))

  for (const r of reports) {
    if (r.error) { console.log(`${r.pod}\tERROR\t${r.error}`); continue }
    console.log([r.pod, `rows=${r.rows}`, `relabel=${r.relabelCount}`,
      `before(ex)=${r.baselineDeliveredCollisions.exchangePairs}p/${r.baselineDeliveredCollisions.exchangeTurns}t`,
      `after(ex)=${r.proposedExchangeCollisions.pairs}p/${r.proposedExchangeCollisions.turns}t`,
      `regen=${r.regenLines}(mine=${r.regenCausedByThisRecast}/drift=${r.regenPreexistingDrift})`,
      `clips=${r.regenDistinctClips}`, `kept=${r.deliveredClipsKeptByOrientation}`,
      `voices=${r.voicePairTarget.distinct}`,
      r.blockers.length ? `BLOCKED: ${r.blockers.join(' | ')}` : 'ok',
    ].join('\t'))
  }
  console.log(`\nlog: ${out}`)
  await db.end()
}

