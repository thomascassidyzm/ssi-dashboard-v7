function sceneUniqueName(row) {
  const canon = canonicalSpeakerName(row.speaker)
  const map = RELABEL[row.scene_number]
  return (map && map[canon]) || canon
}

function sceneLists(rows, nameOf) {
  const m = new Map()
  for (const r of rows) {
    if (!m.has(r.scene_number)) m.set(r.scene_number, [])
    m.get(r.scene_number).push(nameOf(r))
  }
  return [...m.values()]
}

/** Turn weights restricted to genuine exchanges (drops the NON_EXCHANGE pairs). */
function buildExchangeWeights(rows, nameOf) {
  const w = new Map()
  const dropped = []
  for (let i = 1; i < rows.length; i++) {
    const prev = rows[i - 1], cur = rows[i]
    if (prev.scene_number !== cur.scene_number) continue
    const a = nameOf(prev), b = nameOf(cur)
    if (!a || !b || a === b) continue
    const tag = `${prev.scene_number}:${prev.sentence_number}->${cur.scene_number}:${cur.sentence_number}`
    if (NON_EXCHANGE.has(tag)) { dropped.push({ tag, a, b, aText: prev.known_text, bText: cur.known_text }); continue }
    const key = a < b ? `${a}|${b}` : `${b}|${a}`
    w.set(key, (w.get(key) || 0) + 1)
  }
  return { weights: w, dropped }
}

/**
 * Two-colour the exchange graph. Returns { colour: Map<name,0|1>, oddCycle }.
 * Each connected component is coloured independently; isolated speakers (no
 * exchange edge at all) land in their own component and are free.
 */
function twoColour(weights, allNames) {
  const adj = new Map(allNames.map(n => [n, new Set()]))
  for (const key of weights.keys()) {
    const [a, b] = key.split('|')
    if (!adj.has(a)) adj.set(a, new Set())
    if (!adj.has(b)) adj.set(b, new Set())
    adj.get(a).add(b); adj.get(b).add(a)
  }
  const colour = new Map()
  const components = []
  let oddCycle = null
  for (const start of adj.keys()) {
    if (colour.has(start)) continue
    const comp = []
    colour.set(start, 0); comp.push(start)
    const q = [start]
    while (q.length) {
      const n = q.shift()
      for (const m of adj.get(n)) {
        if (!colour.has(m)) { colour.set(m, 1 - colour.get(n)); comp.push(m); q.push(m) }
        else if (colour.get(m) === colour.get(n) && !oddCycle) oddCycle = { a: n, b: m }
      }
    }
    components.push(comp)
  }
  return { colour, components, oddCycle }
}

/** Gender the script fixes for a speaker label, or null. */
function scriptGender(label, variants) {
  for (const v of variants || []) { const g = extractGenderMarker(v); if (g === 'f' || g === 'm') return g }
  const base = label.replace(/^(Cafe|Bar)\s+/, '')
  if (NAME_GENDER[base] === 'f' || NAME_GENDER[base] === 'm') return NAME_GENDER[base]
  return null
}

