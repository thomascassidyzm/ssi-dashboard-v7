#!/usr/bin/env node
// Write the ONE Drill pieces data (jobs #252, #577, #628, #671): the plans, recorded.json and ita/clips.json in, and these
// out, all regenerable, none hand-edited:
//   <app>/packages/player-vue/src/data/podDrillPieces/<course>.json   one lazy chunk per course, {turns:{rowId:[DrillPiece,...]}}
//     recorded pieces where a scene 1-10 turn's plan splits it, and nothing else: a turn with no pieces plays its whole
//     sentence (Tom r-2026-11-08: scenes 1-10 recorded pieces, scene 11 on full sentences). It is the only thing Drill reads.
//     No span of a whole take is ever wired (job #671 retired the span cuts: "they sound bad").
//   ops/pod-drill/served/<course>.json   the SAME bytes, Popty's own copy of what the app serves: pod search reads it
//   ops/pod-drill/wired.json             the per-course count, what was left whole and why
// Pod text comes read-only from Popty's pod-scripts route, as turns.cjs and record.cjs read it.
//   node tools/pods/pod-drill/pieces/wire-staging.cjs --app <ssi-learning-app checkout>          write
//   node tools/pods/pod-drill/pieces/wire-staging.cjs --app <ssi-learning-app checkout> --check  write nothing, fail if the files on disk differ
// A piece with either side unresolved leaves its whole turn playing as today, listed, and the run exits 1.
// Refuses, writing nothing, to wire fewer pieces for a course than its file already holds: pass --allow-shrink to mean it.
// Welsh is not in the plans and is never recorded (HUMAN_VOICE_COURSE): its file is written with no turns, so it drills whole.
// NO TRIAL CLIP REACHES A LEARNER (job #628): every trial_ id (recorded.json from before podSide, ita/clips.json) is mapped
// to its pod-only course_audio row through Popty's ops/pod-audio-rows/trial-to-row.json; a new render with podSide is
// already a row in recorded.json. A trial_ id with no row refuses the whole run, writing nothing.
// The app's old trial-proxy allow-list (api/_utils/stagingDrillPieceClips.data.ts) is no longer written: the data names rows.
const fs = require('fs'), path = require('path');
const { DATA: dir, SERVED, ROW_MAP, APP_DATA_REL, planDir, plannedCourses, appRoot } = require('./paths.cjs');
const root = appRoot();
const OUT = path.join(root, APP_DATA_REL);
const { piecesJson } = require('./pieces-format.cjs');
const master = require('./master.cjs');
const WIRED = path.join(dir, 'wired.json');
const rowMap = JSON.parse(fs.readFileSync(ROW_MAP, 'utf8'));
// The note the served files carry, unchanged from the app-side generator and apply-row-ids.cjs, so the move is byte-identical.
const NOTE = 'GENERATED by Popty tools/pods/pod-drill/pieces/wire-staging.cjs (jobs #252, #299, #577, #628, #671). Recorded pieces for the scene 1-10 turns a plan splits; every other turn plays its whole sentence. Clip ids are Popty pod-only course_audio rows.';
const check = process.argv.includes('--check'), allowShrink = process.argv.includes('--allow-shrink');
const letters = (t) => String(t || '').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{M}\p{N}]+/gu, '');
const PLANNED = plannedCourses();
// Courses with no plan (Welsh) keep a file with no turns, so Popty's pod search reads "no pieces", not "unknown".
const WHOLE_ONLY = ['cym_n_for_eng', 'cym_s_for_eng'];
const COURSES = [...new Set([...PLANNED, ...WHOLE_ONLY])].sort();
if (PLANNED.some((c) => c.startsWith('cym'))) throw new Error('Welsh has a plan folder: this tool must not wire it');
const reused = new Set(); // ita's whole-take course clips (#82): wired, but not recorded pieces, so not counted as clips
const recorded = JSON.parse(fs.readFileSync(path.join(dir, 'recorded.json'), 'utf8'));
const ita = JSON.parse(fs.readFileSync(path.join(dir, 'ita/clips.json'), 'utf8'));

// One [targetClip, knownClip] per planned piece of one turn, in plan order, or a reason there is not.
function clipsFor(course, turn) {
  // Italian's scenes 1-5 come from ita/clips.json (#63, #82); its scenes 6-10 were recorded like every other course (#299).
  // A turn replanned to the cut master (job #577) no longer matches clips.json and is wired from recorded.json instead.
  const t0 = course === 'ita_for_eng' ? ita.turns.find((x) => x.id === turn.id && x.pieces) : null;
  const t = t0 && t0.pieces.length === turn.pieces.length && t0.pieces.every((p, i) => p.it && p.en && p.it.text === turn.pieces[i][0] && p.en.text === turn.pieces[i][1]) ? t0 : null;
  if (t) {
    if (t.pieces.length !== turn.pieces.length) return { why: 'ita/clips.json has no matching pieces' };
    const out = [];
    for (let i = 0; i < t.pieces.length; i++) {
      const p = t.pieces[i], [tg, kn] = turn.pieces[i];
      if (!p.it || p.it.text !== tg || !p.en || p.en.text !== kn) return { why: `piece ${i} text differs from clips.json` };
      // reuseWholeTake: the turn's own course clip already says exactly this piece (#82), so it needs no allow-listing.
      const it = p.it.trialClip || p.it.reuseWholeTake;
      if (!p.it.trialClip && p.it.reuseWholeTake) reused.add(p.it.reuseWholeTake);
      if (!it || !p.en.trialClip) return { why: `piece ${i} has no clip on one side` };
      out.push([it, p.en.trialClip]);
    }
    return { clips: out };
  }
  const uses = (recorded.uses[course] || []).filter((u) => u.turn === turn.id);
  if (uses.length !== turn.pieces.length * 2) return { why: `recorded.json lists ${uses.length} sides for ${turn.pieces.length} pieces` };
  const out = [];
  for (let i = 0; i < turn.pieces.length; i++) {
    const t = uses[i * 2], k = uses[i * 2 + 1], [tg, kn] = turn.pieces[i];
    if (t.side !== 'target' || k.side !== 'known') return { why: `piece ${i} sides out of order` };
    if (t.key.split('|').slice(1).join('|') !== tg || k.key.split('|').slice(1).join('|') !== kn) return { why: `piece ${i} text differs from the recording` };
    const tc = recorded.clips[t.key], kc = recorded.clips[k.key];
    if (!tc || !tc.audioId || !kc || !kc.audioId) return { why: `piece ${i} has no clip on the ${tc && tc.audioId ? 'known' : 'target'} side` };
    out.push([tc.audioId, kc.audioId]);
  }
  return { clips: out };
}

(async () => {
  const summary = {}, files = {}, unresolved = [], ids = new Set(), masterRed = [];
  for (const course of COURSES) {
    if (!PLANNED.includes(course)) {
      summary[course] = { turns: 0, whole: 0, split: 0, pieces: 0, unresolved: [] };
      files[course] = piecesJson({ course, note: NOTE }, {});
      continue;
    }
    const plan = JSON.parse(fs.readFileSync(path.join(dir, planDir(course), 'plan.json'), 'utf8'));
    if (plan.throughScene !== 10) throw new Error(`${course}: plan runs through scene ${plan.throughScene}, not 10`);
    const d = await (await fetch(`http://localhost:3470/api/pod-scripts/${course}`, { signal: AbortSignal.timeout(30000) })).json();
    if (d.slug !== 'pod-1') throw new Error(`${course}: slug ${d.slug}`);
    const lines = new Map();
    for (const s of d.scenes) for (const l of s.lines) lines.set(l.id.split(':').pop(), l);
    const turns = {}, s = { turns: plan.turns.length, whole: 0, split: 0, pieces: 0, unresolved: [] };
    for (const t of plan.turns) {
      // The one cut master (job #577): a plan whose English is not the master's pieces or listed joins is refused.
      const ml = lines.get(t.id);
      if (ml) for (const r of master.checkTurn(course, plan, t, master.englishSide(course) === 0 ? ml.target_text : ml.known_text).red) masterRed.push(`${course} ${r}`);
      if (!t.pieces) { s.whole++; continue; }
      const l = lines.get(t.id);
      const miss = (why) => { s.whole++; s.unresolved.push({ turn: t.id, why }); unresolved.push(`${course} ${t.id}: ${why}`); };
      if (!l) { miss('no such turn in the pod'); continue; }
      if (l.scene_number > 10) { miss(`scene ${l.scene_number}, past scene 10`); continue; }
      if (letters(t.pieces.map((p) => p[0]).join('')) !== letters(l.target_text)) { miss('target pieces do not join back to the turn'); continue; }
      // Italian's rebalanced English in scenes 1-5 is reworded to match its Italian order (#82: "Yes, today I have"), so only the rest join.
      if (!(course === 'ita_for_eng' && l.scene_number <= 5) && letters(t.pieces.map((p) => p[1]).join('')) !== letters(l.known_text)) { miss('known pieces do not join back to the turn'); continue; }
      const r = clipsFor(course, t);
      if (r.why) { miss(r.why); continue; }
      turns[l.id] = t.pieces.map(([tg, kn], i) => [tg, kn, r.clips[i][0], r.clips[i][1]]);
      for (const pair of r.clips) for (const id of pair) if (!reused.has(id)) ids.add(id);
      s.split++; s.pieces += t.pieces.length;
    }
    summary[course] = s;
    files[course] = piecesJson({ course, note: NOTE }, Object.fromEntries(Object.entries(turns).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))));
  }
  if (masterRed.length) { console.error(`REFUSED: ${masterRed.length} turn(s) do not follow the cut master (master.cjs). Nothing written.\n${masterRed.join('\n')}`); process.exit(4); }
  // Trial ids to pod rows, in the files' own text (the apply-row-ids.cjs rule, _xNN variants included).
  const unmapped = new Set();
  const toRows = (body) => body.replace(/"(trial_[0-9A-Fa-f-]{36}(?:_x\d{2,3})?)"/g, (whole, id) => {
    const m = rowMap[id];
    if (!m || !m.audioId) { unmapped.add(id); return whole; }
    return `"${m.audioId}"`;
  });
  for (const c of COURSES) files[c] = toRows(files[c]);
  if (unmapped.size) { console.error(`REFUSED: ${unmapped.size} trial_ id(s) have no pod row in ${path.relative(path.join(dir, '..', '..'), ROW_MAP)} (${[...unmapped].slice(0, 5).join(' ')}): file them first (tools/pods/file-pod-audio.cjs). Nothing written.`); process.exit(2); }
  const wired = JSON.stringify({ note: 'GENERATED by wire-staging.cjs', clips: ids.size, courses: summary }, null, 1) + '\n';
  const outputs = [[WIRED, wired], ...COURSES.map((c) => [path.join(SERVED, `${c}.json`), files[c]]), ...COURSES.map((c) => [path.join(OUT, `${c}.json`), files[c]])];
  const stale = outputs.filter(([f, body]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== body).map(([f]) => f);
  if (check) {
    if (stale.length) { console.error(`STALE: ${stale.join(' ')}`); process.exit(1); }
  } else {
    for (const c of COURSES) {
      const f = path.join(OUT, `${c}.json`);
      if (!fs.existsSync(f) || allowShrink) continue;
      const had = Object.values(JSON.parse(fs.readFileSync(f, 'utf8')).turns).flat().length;
      if (summary[c].pieces < had) { console.error(`REFUSED: ${c} would shrink from ${had} pieces to ${summary[c].pieces}. Nothing written.`); process.exit(2); }
    }
    // Last guard (job #628): nothing is written while any output would still name a trial_ clip.
    const trialHeld = outputs.filter(([, body]) => /"trial_[0-9A-Fa-f-]{36}/.test(body)).map(([f]) => path.basename(f));
    if (trialHeld.length) {
      console.error(`REFUSED: ${trialHeld.length} file(s) would name trial_ clips (${trialHeld.slice(0, 5).join(', ')}) — the served data names Popty pod rows (job #628). File them as rows (tools/pods/file-pod-audio.cjs) first. Nothing written.`);
      process.exit(2);
    }
    fs.mkdirSync(OUT, { recursive: true }); fs.mkdirSync(SERVED, { recursive: true });
    for (const [f, body] of outputs) fs.writeFileSync(f, body);
  }
  const n = Object.values(summary);
  console.log(`${COURSES.length} courses, ${n.reduce((a, s) => a + s.split, 0)} split turns, ${n.reduce((a, s) => a + s.pieces, 0)} pieces, ${ids.size} clip ids, ${unresolved.length} unresolved`);
  if (unresolved.length) { console.error(`UNRESOLVED, left whole:\n${unresolved.join('\n')}`); process.exit(1); }
})().catch((e) => { console.error(String(e)); process.exit(3); });
