#!/usr/bin/env node
// Fold the retired span-cut files into the ONE drill shape (job #577, Tom r-2026-11-07-ssi-pods-exactly-one-way-of).
// Reads packages/player-vue/src/data/podDrillCuts/<course>.json AT A GIT REF (the files are deleted from the tree by
// the same job) and writes Popty ops/pod-drill/spans/<course>.json: {turns:{sentenceId:[DrillPiece,...]}}, the
// span pieces wire-staging.cjs merges under the recorded pieces. A sentence whose turn has recorded pieces is left
// out: the recorded pieces are the drill there (decision, job #577).
//   node tools/pods/pod-drill/pieces/fold-span-cuts.cjs --app <ssi-learning-app checkout> [--ref 27aace16ba]   (git is read in the app)
// DrillPiece = [target, known, targetClip, knownClip|null, [tStart,tEnd]|null, [kStart,kEnd]|null, {kFor?, lineKnown?}]
// knownClip null = the line's own English clip, named by id when the card is built. A chunk whose English had no cut
// of its own (it was looked up by its gloss text, or had none) says its line's English, marked lineKnown.
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const { DATA: dir, appRoot } = require('./paths.cjs'), root = appRoot();
const ref = (process.argv.includes('--ref') && process.argv[process.argv.indexOf('--ref') + 1]) || '27aace16ba';
const CUTS = 'packages/player-vue/src/data/podDrillCuts';
const RECORDED = 'packages/player-vue/src/data/stagingDrillPieces';
const git = (...a) => execFileSync('git', a, { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] });
const { piecesJson } = require('./fold-span-cuts-format.cjs');
const ok = (a, b) => Number.isFinite(a) && Number.isFinite(b) && a < b;
const files = git('ls-tree', '--name-only', `${ref}:${CUTS}`).split('\n').filter((f) => f.endsWith('.json'));
const OUT = path.join(dir, 'spans');
fs.mkdirSync(OUT, { recursive: true });
const report = {};
for (const f of files) {
  const course = f.replace(/\.json$/, '');
  const cuts = JSON.parse(git('show', `${ref}:${CUTS}/${f}`)).sentences || {};
  let recorded = {};
  try { recorded = JSON.parse(git('show', `${ref}:${RECORDED}/${f}`)).turns || {}; } catch { /* none */ }
  const turns = {}, r = { sentences: 0, pieces: 0, lineKnown: 0, skippedRecorded: 0, skippedNoCut: 0 };
  for (const [sid, cut] of Object.entries(cuts)) {
    if (recorded[sid.split(':s')[0]]) { r.skippedRecorded++; continue; }
    const lines = cut.lines || [];
    const multi = lines.length > 1;
    if (!lines.length || (!multi && (lines[0].chunks || []).length < 2)) { r.skippedNoCut++; continue; }
    const kFor = cut.knownTwinOf || cut.knownClip || null;
    const lineEnglish = (l) => {
      if (!multi) return { k: null, span: null };
      if (l.kc) return { k: l.kc, span: null };
      if (cut.knownClip && l.k && l.k.length === 3 && ok(l.k[1], l.k[2])) return { k: cut.knownClip, span: [l.k[1], l.k[2]] };
      return { k: null, span: null };
    };
    const pieces = [];
    for (const l of lines) {
      const chunks = (l.chunks || []).length >= 2 ? l.chunks : null;
      const le = lineEnglish(l);
      if (!chunks) {
        const opts = le.span ? { kFor } : {};
        pieces.push([l.t[0], (l.k && l.k[0]) || '', cut.clip, le.k, [l.t[1], l.t[2]], le.span, ...(Object.keys(opts).length ? [opts] : [])]);
        continue;
      }
      for (const [text, s, e, gloss, ks, ke, standalone] of chunks) {
        if (typeof standalone === 'string' && standalone) { pieces.push([text, gloss || '', cut.clip, standalone, [s, e], null]); continue; }
        if (cut.knownClip && ks != null && ke != null && ok(ks, ke)) { pieces.push([text, gloss || '', cut.clip, cut.knownClip, [s, e], [ks, ke], { kFor }]); continue; }
        r.lineKnown++;
        pieces.push([text, gloss || (multi ? (l.k && l.k[0]) || '' : ''), cut.clip, le.k, [s, e], le.span, { lineKnown: true, ...(le.span ? { kFor } : {}) }]);
      }
    }
    turns[sid] = pieces;
    r.sentences++; r.pieces += pieces.length;
  }
  report[course] = r;
  fs.writeFileSync(path.join(OUT, f), piecesJson({ course, note: `GENERATED by fold-span-cuts.cjs (now Popty tools/pods/pod-drill/pieces/) from ${CUTS}/${f} at ${ref} (job #577). Span pieces of recordings that are not re-recorded: the frozen Welsh takes, and turns awaiting recording.` }, turns));
}
console.log(JSON.stringify(report, null, 1));
