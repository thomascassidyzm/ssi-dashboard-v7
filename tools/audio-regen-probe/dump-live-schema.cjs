#!/usr/bin/env node
/**
 * Dump the LOAD-BEARING audio-identity schema out of the live database, verbatim,
 * into schema.sql so the isolated PGlite fixture is not a paraphrase.
 *
 * READ-ONLY. It issues nothing but SELECTs against pg_proc / information_schema.
 * It is NOT run by the tests — the tests read the committed schema.sql and never
 * touch the network. Re-run this by hand when the live triggers change:
 *
 *   node tools/audio-regen-probe/dump-live-schema.cjs > tools/audio-regen-probe/schema.sql
 */
const fs = require('fs')
const path = require('path')
const { Client } = require('pg')

const REPO = path.resolve(__dirname, '../..')
const envPsql = fs.readFileSync(path.join(REPO, '.env.psql'), 'utf8')
const url = (envPsql.match(/DATABASE_URL\s*=\s*(.+)/) || [])[1].trim().replace(/^["']|["']$/g, '')

// Functions the defect actually runs through. Everything else on these tables
// (audit_content_change, touch_*_stamp, increment_version, bump_course_version)
// is bookkeeping that cannot change which audio row a slot points at, and is
// deliberately omitted — see schema.sql's header.
const FUNCTIONS = [
  'normalize_text',
  'canonical_language',
  'canonical_voice_id',
  'audio_canon_voice',
  'audio_id_for_text',
  'audio_id_for_text_same_voice',
  'audio_normalize_text',
  'course_audio_canonical_identity',
  'link_audio_to_content',
  'null_lego_audio_on_text_change',
  'null_phrase_audio_on_text_change',
  'null_seed_audio_on_text_change',
  'pull_audio_duration_on_link',
  // Added 2026-08-18 for the unlink-then-generate reproduction: this is the RPC
  // /generate Step A (phase8:1985) calls BEFORE it ever asks what needs TTS.
  'link_all_audio_ids',
]

const TRIGGER_TABLES = ['course_audio', 'course_legos', 'course_practice_phrases', 'course_seeds']
const KEEP_TRIGGERS = new Set([
  'trg_course_audio_normalize',
  'trg_course_audio_canonical_identity',
  'audio_autolink',
  'trg_null_lego_audio_on_text_change',
  'trg_null_phrase_audio_on_text_change',
  'trg_null_seed_audio_on_text_change',
  'course_legos_pull_duration',
  'course_practice_phrases_pull_duration',
])

;(async () => {
  const c = new Client({ connectionString: url, ssl: { rejectUnauthorized: false } })
  await c.connect()
  const out = []
  out.push('-- GENERATED by tools/audio-regen-probe/dump-live-schema.cjs — do not hand-edit.')
  out.push('-- Function bodies and trigger definitions below are pg_get_functiondef /')
  out.push('-- pg_get_triggerdef output from the LIVE database, verbatim.')
  out.push('--')
  out.push('-- Deliberately omitted (bookkeeping only; cannot change which audio row a')
  out.push('-- content slot points at): audit_content_change, touch_course_content_stamp,')
  out.push('-- touch_course_audio_stamp, increment_version, bump_course_version,')
  out.push('-- sync_audio_duration_to_dependents, refuse_component_introduction.')
  out.push('')

  const dumped = await c.query(`select now() at time zone 'utc' as t`)
  out.push(`-- dumped_at_utc: ${dumped.rows[0].t.toISOString()}`)
  out.push('')

  // --- tables (hand-authored DDL, column lists checked against information_schema) ---
  out.push(fs.readFileSync(path.join(__dirname, 'tables.sql'), 'utf8'))

  // --- language_canonical seed rows, for canonical_language() ---
  const lc = await c.query(
    `select raw, canonical from language_canonical where raw in ('en','es','cy','fr','de','eng','spa','cym','fra','deu') order by raw`)
  out.push('-- language_canonical rows copied from live (only the codes the tests use)')
  for (const r of lc.rows) {
    out.push(`INSERT INTO language_canonical (raw, canonical) VALUES ('${r.raw}', '${r.canonical}');`)
  }
  out.push('')

  // --- functions ---
  for (const f of FUNCTIONS) {
    const r = await c.query(
      `select pg_get_functiondef(p.oid) def from pg_proc p
        join pg_namespace n on n.oid = p.pronamespace
       where n.nspname = 'public' and p.proname = $1`, [f])
    if (!r.rows[0]) throw new Error(`function ${f} not found in live DB`)
    out.push(`-- ===== ${f} =====`)
    out.push(r.rows[0].def.trimEnd() + ';')
    out.push('')
  }

  // --- triggers ---
  const t = await c.query(
    `select t.tgname, pg_get_triggerdef(t.oid) def
       from pg_trigger t join pg_class c on c.oid = t.tgrelid
      where not t.tgisinternal and c.relname = any($1)`, [TRIGGER_TABLES])
  out.push('-- ===== triggers =====')
  for (const row of t.rows.filter(r => KEEP_TRIGGERS.has(r.tgname))) {
    out.push(row.def + ';')
  }
  out.push('')

  // --- the identity constraint ---
  const u = await c.query(
    `select pg_get_constraintdef(oid) def from pg_constraint
      where conrelid = 'public.course_audio'::regclass and conname = 'unique_course_audio_per_voice'`)
  out.push('-- ===== the clip-identity constraint =====')
  out.push(`ALTER TABLE course_audio ADD CONSTRAINT unique_course_audio_per_voice ${u.rows[0].def};`)
  out.push('')

  await c.end()
  process.stdout.write(out.join('\n'))
})().catch(e => { console.error(e); process.exit(1) })
