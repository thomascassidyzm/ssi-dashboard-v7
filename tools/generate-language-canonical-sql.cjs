#!/usr/bin/env node
/**
 * Generate the `language_canonical` lookup rows for the DB-side canonicaliser.
 *
 *   node tools/generate-language-canonical-sql.cjs <out.sql>
 *
 * Takes an output PATH rather than writing to stdout: requiring
 * language-code-service.cjs prints its load banner to stdout, which would end
 * up in the middle of the SQL.
 *
 * The database needs to canonicalise a language code without being able to call
 * JavaScript, and the language map lives in a CSV that only JavaScript reads.
 * Rather than hand-write a second map — two maps to keep in step is the exact
 * bug this whole exercise removes — the SQL side gets a TABLE generated from the
 * one map, by the one canonicaliser.
 *
 * Source of truth: services/shared/clip-identity.cjs over
 * tools/sync/reference/language_codes.csv. Rows are every primary subtag that
 * could reach the column: every database_code, every manifest/ISO-639-1 code,
 * and every primary subtag of every Azure locale.
 *
 * `services/shared/clip-identity.test.js` asserts the generator and the module
 * agree; `database/migrations/20260806_clip_identity_canonical.sql` holds the
 * generated output. Regenerate and diff whenever the CSV changes.
 */

const fs = require('fs');
const path = require('path');
const { canonicalLanguage, tryCanonicalLanguage } = require('../services/shared/clip-identity.cjs');

const CSV = path.join(__dirname, 'sync', 'reference', 'language_codes.csv');

/** Every primary subtag that could plausibly arrive in the column. */
function candidates() {
  const set = new Set();
  const lines = fs.readFileSync(CSV, 'utf8').trim().split('\n').slice(1);
  for (const line of lines) {
    // Names containing commas are quoted; a crude split is enough here because
    // we only want the code columns, and we take them from both ends.
    const parts = line.split(',');
    const manifest = (parts[0] || '').trim().toLowerCase();
    const dbCode = (parts[parts.length - 2] || '').trim().toLowerCase();
    const azure = line.match(/,([a-z]{2,3}-[A-Za-z]{2,4}),/);
    if (manifest) set.add(manifest);
    if (dbCode) set.add(dbCode);
    if (azure) set.add(azure[1].split('-')[0].toLowerCase());
  }
  // The estate's own codes, in case the CSV ever loses one.
  for (const c of ['eng', 'zho', 'cmn', 'zh', 'ell', 'el']) set.add(c);
  return [...set].filter(Boolean).sort();
}

function rows() {
  const out = [];
  for (const raw of candidates()) {
    const canonical = tryCanonicalLanguage(raw);
    if (canonical) out.push([raw, canonical]);
  }
  return out;
}

/** The generated INSERT, as a string. */
function sql() {
  const values = rows()
    .map(([a, b]) => `  ('${a}','${b}')`)
    .join(',\n');
  return (
    `-- generated by tools/generate-language-canonical-sql.cjs — do not hand-edit\n` +
    `INSERT INTO language_canonical (raw, canonical) VALUES\n${values}\n` +
    `ON CONFLICT (raw) DO UPDATE SET canonical = EXCLUDED.canonical;\n`
  );
}

if (require.main === module) {
  const out = process.argv[2];
  if (!out) {
    process.stderr.write('usage: node tools/generate-language-canonical-sql.cjs <out.sql>\n');
    process.exit(2);
  }
  fs.writeFileSync(out, sql());
  process.stderr.write(`${rows().length} rows -> ${out}\n`);
}

module.exports = { rows, candidates, sql, canonicalLanguage };
