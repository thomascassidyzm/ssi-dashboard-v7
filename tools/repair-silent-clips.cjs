#!/usr/bin/env node
/**
 * repair-silent-clips.cjs — re-render course_audio clips that contain no speech
 * (or only half of it), and heal every link to them.
 *
 * WHY (2026-08-03, fra_for_eng): a long xAI batch degraded and began answering
 * with empty or truncated HTTP 200 bodies. `response.ok` passed them, the
 * mastering chain laundered them into well-formed MP3s, and duration_ms was
 * computed FROM those files — so the row and the object agreed perfectly and
 * every consistency check in the estate passed. 539 clips shipped as digital
 * silence and ~300 more as half-sentences.
 *
 * Input is the repair list from `tools/audio-batch-gate.cjs --out`.
 *
 *   node tools/repair-silent-clips.cjs fra_for_eng --flags /tmp/fra-repair.json --dry
 *   node tools/repair-silent-clips.cjs fra_for_eng --flags /tmp/fra-repair.json --limit 6
 *   node tools/repair-silent-clips.cjs fra_for_eng --flags /tmp/fra-repair.json
 *
 * TTS costs money. Run only under an approved plan (this repair is approved:
 * Tom 2026-08-04). Idempotent: a re-run skips ids that no longer exist.
 *
 * ── Why the id changes ──────────────────────────────────────────────────────
 * The clip is NOT refreshed under its existing id. The learning app serves audio
 * from /api/audio/:audioId with `Cache-Control: public, max-age=31536000,
 * immutable` (ssi-learning-app/api/audio/[audioId].ts:150) and caches offline
 * blobs in IndexedDB keyed by audio id (packages/player-vue/src/cache/
 * AudioCache.ts). A device that has already streamed or downloaded the silent
 * bytes holds them under that id for a year, and no amount of fresh bytes at the
 * same id would ever reach it. Minting a new id is what actually heals a device.
 * (The service worker is NOT part of this — it deliberately stopped caching
 * audio in 2026-05-24; the browser's own HTTP cache is the layer that bites.)
 *
 * ── What that costs, and the guards it needs ────────────────────────────────
 * A new id means the old row must go (the unique key
 * course_code+text_normalized+language+role+voice_id is what forces this), and
 * every foreign key to it must be re-pointed. Live constraint check, 2026-08-04:
 *
 *   SET NULL  course_legos / course_practice_phrases / course_seeds
 *             .{known,target1,target2}_audio_id       <- captured and relinked here
 *   SET NULL  listening_pod_sentences.{known,target}_audio_id
 *   CASCADE   course_audio_envelope.audio_id          <- regenerated by the
 *             envelope backfill; losing it is a no-op
 *   CASCADE   lego_introductions.presentation_audio_id <- DESTROYS AUTHORED
 *             CONTENT. This tool therefore REFUSES role='presentation', always.
 *
 * The FK is SET NULL, so the links are gone the instant the delete lands —
 * they are captured BEFORE the delete and restored after the insert.
 *
 * Duration is denormalised onto course_legos/course_practice_phrases as
 * target1_duration_ms / target2_duration_ms, and the player sizes the PAUSE
 * between cycles from those numbers. A repair that fixed the audio but left the
 * stale 144 ms sitting in those columns would leave the collapsed pause in
 * place — the second symptom Tom actually heard. They are updated here too.
 *
 * ── The order of operations ─────────────────────────────────────────────────
 * Render and VERIFY first, mutate second. The clip is re-rendered, mastered and
 * proven to contain speech before a single row is touched; only then is the old
 * row swapped out. A failed render therefore costs nothing and breaks nothing.
 * If the insert itself fails, the old row is restored from its untouched S3
 * object and its links are put back.
 */
require('dotenv').config({ path: require('path').join(__dirname, '..', '.env') })
const fs = require('fs')
const os = require('os')
const path = require('path')
const { execFile } = require('child_process')
const { v4: uuidv4 } = require('uuid')
const { PutObjectCommand } = require('@aws-sdk/client-s3')
const { createClient } = require('@supabase/supabase-js')
const ttsService = require('../services/tts-service.cjs')
const p8 = require('../services/phases/phase8-audio-v13.cjs')
const { toBcp47 } = require('../services/voice-discovery-service.cjs')
const { isHumanVoiceCourse } = require('../services/shared/human-voice-courses.cjs')

const argv = process.argv.slice(2)
const arg = (f, d = null) => { const i = argv.indexOf(f); return i !== -1 && argv[i + 1] ? argv[i + 1] : d }
const COURSE = argv[0] && !argv[0].startsWith('--') ? argv[0] : null
const FLAGS = arg('--flags')
const ONLY = arg('--only', 'all')            // confirmed | suspect | all
const LIMIT = Number(arg('--limit', 0)) || 0
const DRY = argv.includes('--dry')
const ATTEMPTS = Number(arg('--attempts', 3))

if (!COURSE || !FLAGS) {
  console.error('usage: repair-silent-clips.cjs <course> --flags <repair.json> [--only confirmed|suspect|all] [--limit N] [--attempts N] [--dry]')
  process.exit(1)
}
if (isHumanVoiceCourse(COURSE)) {
  console.log(`${COURSE} is human-voiced only — no TTS ever (Tom 2026-07-25). Nothing to do.`)
  process.exit(0)
}

const supabase = createClient(
  (process.env.SUPABASE_URL || '').trim(),
  (process.env.SUPABASE_SERVICE_KEY || '').trim(),
  { auth: { persistSession: false, autoRefreshToken: false } },
)

const FFMPEG = process.env.FFMPEG || 'ffmpeg'
/** A repaired clip must clear this to land. Same floor as the batch gate. */
const FLOOR_MS = 400
/** ...and must be at least this fraction of what a fresh render implies, which
 *  is what catches TRUNCATION. A re-render of the same text at the same voice
 *  varies by a few percent, never by half. */
const TRUNCATION_RATIO = 0.75
/** Below this mean level the clip is silence, not speech (stubs read -91 dB). */
const SILENCE_MEAN_DB = -60

/** Tables/columns that point at a course_audio id, all ON DELETE SET NULL. */
const LINK_TABLES = [
  { table: 'course_legos', cols: ['known_audio_id', 'target1_audio_id', 'target2_audio_id'], durations: true },
  { table: 'course_practice_phrases', cols: ['known_audio_id', 'target1_audio_id', 'target2_audio_id'], durations: true },
  { table: 'course_seeds', cols: ['known_audio_id', 'target1_audio_id', 'target2_audio_id'], durations: false },
]
/** Roles this tool will never touch: deleting one CASCADEs into authored content. */
const FORBIDDEN_ROLES = new Set(['presentation'])

/** Peak/mean level of a file via ffmpeg volumedetect. null = unmeasurable. */
function measureLevel(file) {
  return new Promise(resolve => {
    execFile(FFMPEG, ['-hide_banner', '-nostats', '-i', file, '-af', 'volumedetect', '-f', 'null', '-'],
      { encoding: 'utf8', maxBuffer: 1 << 22 }, (_e, _o, stderr) => {
        const mean = /mean_volume:\s*(-?[\d.]+) dB/.exec(stderr || '')
        const peak = /max_volume:\s*(-?[\d.]+) dB/.exec(stderr || '')
        resolve(mean && peak ? { meanDb: parseFloat(mean[1]), peakDb: parseFloat(peak[1]) } : null)
      })
  })
}

/** The provider + bare voice id behind a stored voice_id like 'xai_leo'. */
function decodeVoiceId(storedVoiceId) {
  const m = /^(xai|azure|elevenlabs)_(.+)$/.exec(String(storedVoiceId || ''))
  return m ? { provider: m[1], voiceId: m[2] } : { provider: 'xai', voiceId: String(storedVoiceId || '') }
}

/**
 * Render one clip through the SAME chain the pipeline uses (generateWithRetry ->
 * masterAudio), and prove the result contains speech before returning it.
 *
 * The empty-response gate in tts-service.cjs already re-rolls a silent response
 * inside generateWithRetry's budget. This is the belt to that braces: it checks
 * the MASTERED artefact, which is what actually lands, and it is the only layer
 * that can see truncation (the boundary has no idea how long the clip should be).
 */
async function renderVerified(row, tmpDir, expectedMs) {
  const { provider, voiceId } = decodeVoiceId(row.voice_id)
  let last = null
  for (let attempt = 1; attempt <= ATTEMPTS; attempt++) {
    const { audioBuffer } = await ttsService.generateWithRetry(row.text, provider, {
      apiKey: process.env.XAI_API_KEY,
      voiceId,
      language: toBcp47(row.language),
    })
    const { buffer, durationMs } = await p8.masterAudio(audioBuffer, row.text)

    const probe = path.join(tmpDir, `verify-${row.id}-${attempt}.mp3`)
    fs.writeFileSync(probe, buffer)
    const level = await measureLevel(probe)
    try { fs.unlinkSync(probe) } catch {}

    const silent = level && level.meanDb < SILENCE_MEAN_DB
    const short = durationMs < FLOOR_MS
    const truncated = expectedMs ? durationMs < TRUNCATION_RATIO * expectedMs : false
    last = { buffer, durationMs, level, silent, short, truncated }
    if (!silent && !short && !truncated) return last

    console.log(`      attempt ${attempt}: ${silent ? 'SILENT' : short ? `${durationMs}ms < floor` : `${durationMs}ms vs expected ${expectedMs}ms`} — re-roll`)
  }
  throw new Error(`no attempt produced speech (last: ${last.durationMs}ms, mean ${last.level ? last.level.meanDb : '?'}dB)`)
}

/** Every link to `audioId`, captured before the delete nulls them. */
async function captureLinks(audioId) {
  const links = []
  for (const { table, cols } of LINK_TABLES) {
    for (const col of cols) {
      const { data, error } = await supabase.from(table).select('id').eq(col, audioId)
      if (error) throw new Error(`capture ${table}.${col}: ${error.message}`)
      for (const r of data || []) links.push({ table, col, rowId: r.id })
    }
  }
  return links
}

/** Re-point captured links at the new id, and refresh the denormalised duration. */
async function restoreLinks(links, newId, durationMs) {
  for (const l of links) {
    const patch = { [l.col]: newId }
    const spec = LINK_TABLES.find(t => t.table === l.table)
    // target1_audio_id -> target1_duration_ms. `known` has no duration column.
    const m = /^(target[12])_audio_id$/.exec(l.col)
    if (spec.durations && m) patch[`${m[1]}_duration_ms`] = durationMs
    const { error } = await supabase.from(l.table).update(patch).eq('id', l.rowId)
    if (error) throw new Error(`relink ${l.table}.${l.col}#${l.rowId}: ${error.message}`)
  }
}

;(async () => {
  const flags = JSON.parse(fs.readFileSync(FLAGS, 'utf8'))
  let jobs = flags.filter(f => ONLY === 'all' || f.verdict === ONLY)

  // Hard refusals, stated rather than silently dropped.
  const forbidden = jobs.filter(j => FORBIDDEN_ROLES.has(j.role))
  if (forbidden.length) {
    console.log(`REFUSING ${forbidden.length} role=presentation clip(s): deleting one CASCADEs into lego_introductions and destroys authored content.`)
    jobs = jobs.filter(j => !FORBIDDEN_ROLES.has(j.role))
  }
  const pods = jobs.filter(j => /^pod_/.test(j.role))
  if (pods.length) {
    console.log(`SKIPPING ${pods.length} pod clip(s): pod links live in listening_pod_sentences — that is tools/rescue-wrong-language-clips.cjs's job, not this one.`)
    jobs = jobs.filter(j => !/^pod_/.test(j.role))
  }
  if (LIMIT) jobs = jobs.slice(0, LIMIT)

  console.log(`\nrepair-silent-clips — ${COURSE}`)
  console.log(`${jobs.length} clip${jobs.length === 1 ? '' : 's'} to repair (--only ${ONLY}${LIMIT ? `, --limit ${LIMIT}` : ''})`)
  const byVerdict = jobs.reduce((a, j) => ((a[j.verdict] = (a[j.verdict] || 0) + 1), a), {})
  console.log(`   ${Object.entries(byVerdict).map(([k, v]) => `${k}: ${v}`).join(', ')}\n`)

  if (DRY) {
    for (const j of jobs.slice(0, 40)) {
      console.log(`  [DRY] ${j.verdict.padEnd(9)} ${j.role.padEnd(8)} ${String(j.duration_ms).padStart(5)}ms  ${JSON.stringify(j.text).slice(0, 50)}`)
    }
    if (jobs.length > 40) console.log(`  ... and ${jobs.length - 40} more`)
    console.log(`\nDry run — nothing rendered, nothing written.\n`)
    process.exit(0)
  }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'repair-clips-'))
  let repaired = 0, skippedHealthy = 0, failed = 0, chars = 0, renders = 0
  const log = []

  for (const [i, job] of jobs.entries()) {
    const prefix = `[${i + 1}/${jobs.length}] ${job.role} ${JSON.stringify(job.text).slice(0, 42)}`
    let restore = null
    try {
      const { data: row, error: readErr } = await supabase
        .from('course_audio').select('*').eq('id', job.id).single()
      if (readErr || !row) { console.log(`${prefix}: gone (already repaired?) — skip`); continue }
      if (row.origin === 'human') { console.log(`${prefix}: origin=human — REFUSED`); continue }

      // A suspect clip is audible; only a probe render can say whether it is
      // truncated or simply a fast one. The probe IS the candidate render, so a
      // suspect that turns out fine costs one render and nothing else.
      const expectedMs = null
      const rendered = await renderVerified(row, tmpDir, expectedMs)
      renders++
      chars += String(row.text || '').length

      if (job.verdict === 'suspect' && row.duration_ms >= TRUNCATION_RATIO * rendered.durationMs) {
        console.log(`${prefix}: healthy (${row.duration_ms}ms vs fresh ${rendered.durationMs}ms) — left alone`)
        log.push({ id: job.id, action: 'kept', storedMs: row.duration_ms, freshMs: rendered.durationMs })
        skippedHealthy++
        continue
      }

      // Verified good. Only now do we touch anything.
      const links = await captureLinks(row.id)
      const newId = uuidv4().toUpperCase()
      const s3Key = `mastered/${newId}.mp3`
      await p8.s3.send(new PutObjectCommand({
        Bucket: p8.S3_BUCKET, Key: s3Key, Body: rendered.buffer, ContentType: 'audio/mpeg',
      }))

      const { error: delErr } = await supabase.from('course_audio').delete().eq('id', row.id)
      if (delErr) throw new Error(`delete: ${delErr.message}`)
      restore = { row, links }

      const fresh = { ...row, id: newId, s3_key: s3Key, duration_ms: rendered.durationMs, origin: 'tts' }
      delete fresh.text_stripped     // GENERATED ALWAYS — an explicit value is rejected
      delete fresh.created_at
      delete fresh.updated_at
      const { error: insErr } = await supabase.from('course_audio').insert(fresh)
      if (insErr) throw new Error(`insert: ${insErr.message}`)
      restore = null

      await restoreLinks(links, newId, rendered.durationMs)
      repaired++
      console.log(`${prefix}: ${row.duration_ms}ms -> ${rendered.durationMs}ms (${rendered.level.meanDb}dB), ${links.length} link${links.length === 1 ? '' : 's'} -> ${newId}`)
      log.push({ id: job.id, newId, action: 'repaired', wasMs: row.duration_ms, nowMs: rendered.durationMs, meanDb: rendered.level.meanDb, links: links.length })
    } catch (e) {
      failed++
      console.log(`${prefix}: FAILED — ${e.message.slice(0, 140)}`)
      log.push({ id: job.id, action: 'failed', error: e.message })
      if (restore) {
        const back = { ...restore.row }
        delete back.text_stripped
        const { error: resErr } = await supabase.from('course_audio').insert(back)
        if (resErr) {
          console.log(`   RESTORE FAILED for ${job.id} — DANGLING LINKS, fix by hand: ${resErr.message}`)
        } else {
          await restoreLinks(restore.links, restore.row.id, restore.row.duration_ms).catch(() => {})
          console.log(`   old row ${job.id} restored (its S3 object was never touched)`)
        }
      }
    }
  }
  try { fs.rmSync(tmpDir, { recursive: true, force: true }) } catch {}

  const logPath = `/tmp/repair-${COURSE}-${jobs.length}.json`
  fs.writeFileSync(logPath, JSON.stringify(log, null, 2))
  console.log(`\n${repaired} repaired, ${skippedHealthy} left alone (probe says healthy), ${failed} failed, of ${jobs.length}.`)
  console.log(`${renders} render${renders === 1 ? '' : 's'}, ${chars.toLocaleString()} characters of TTS.`)
  const health = ttsService.getXaiHealth()
  console.log(`xAI health this run: ${health.requests} responses, ${health.stubs} empty (${(health.stubRate * 100).toFixed(2)}%), ${health.cooldowns} cooldown${health.cooldowns === 1 ? '' : 's'}.`)
  console.log(`log -> ${logPath}\n`)
  process.exit(failed ? 2 : 0)
})().catch((e) => { console.error('ERR:', e.message); process.exit(1) })
