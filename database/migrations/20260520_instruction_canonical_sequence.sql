--   2. Add a sequence column to course_audio.
--   3. Backfill course_audio.sequence from shared_audio via text_normalized.
--   4. (Companion code change) CourseDataProvider.getInstructions() ORDERs
--      by sequence, falling back to id for any unsequenced rows.
--
-- Scope: ENGLISH ONLY. Non-English instructions (es/fr/de/ja/etc translations
-- in shared_audio) still have sequence=NULL — those learners stay on the
