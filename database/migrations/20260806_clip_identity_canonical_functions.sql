-- Clip identity, canonical forms — the database half.
--
-- Part 1 of 2. This migration is INERT: it creates a lookup table and three
-- functions and wires them to nothing. No existing row changes, no write
-- behaviour changes. Safe to apply at any time, and it is what the back-fill
-- and the lint need in order to run server-side.
-- Part 2 (20260806_clip_identity_canonical_enforce.sql) attaches the trigger
-- and the constraints, and must NOT be applied until every writer is converted.
--
-- WHY THE DATABASE NEEDS ITS OWN COPY
-- The canonical forms live in services/shared/clip-identity.cjs. Two things
-- write these columns that cannot call it: direct SQL, and any future caller in
-- another repo. A JS-only guard means applying the CHECK constraint turns every
-- writer we missed into a failed insert — silent audio on a live pipeline. A
-- database-side canonicaliser turns the same miss into a corrected insert.
-- That is make-before-break, and it is the pattern the estate already uses for
-- text_normalized (normalize_text + trg_course_audio_normalize).
--
-- HOW THE TWO COPIES ARE KEPT IN STEP
-- They are not two maps. `language_canonical` below is GENERATED from the one
-- map (tools/sync/reference/language_codes.csv) by the one canonicaliser, via
-- tools/generate-language-canonical-sql.cjs, and services/shared/
-- clip-identity.test.js asserts the generator and the module agree. The voice
-- rule is short enough to state directly and is asserted the same way.
--
-- Proven equivalent to the JS on 2026-08-06: all 503 distinct (language,
-- voice_id) values in the live 2.5M-row course_audio agree, both directions,
-- including the values that must RAISE. The proof ran inside a rolled-back
-- transaction against production.
--
-- Rollback: 20260806_clip_identity_canonical_functions.ROLLBACK.sql

BEGIN;

CREATE TABLE IF NOT EXISTS language_canonical (
  raw       text PRIMARY KEY,
  canonical text NOT NULL CHECK (canonical ~ '^[a-z]{3}$')
);

CREATE OR REPLACE FUNCTION canonical_language(code text) RETURNS text
LANGUAGE plpgsql STABLE AS $$
DECLARE primary_subtag text; hit text;
BEGIN
  code := lower(btrim(coalesce(code, '')));
  IF code IN ('', 'auto', 'unknown', 'multi', 'und') THEN
    RAISE EXCEPTION 'clip identity: language % is a placeholder, not a language — resolve it from the course code and role', coalesce(code,'<null>')
      USING ERRCODE = 'check_violation';
  END IF;
  primary_subtag := split_part(regexp_replace(code, '_', '-', 'g'), '-', 1);
  SELECT canonical INTO hit FROM language_canonical WHERE raw = primary_subtag;
  IF hit IS NULL THEN
    RAISE EXCEPTION 'clip identity: language % is not in language_canonical — regenerate it with tools/generate-language-canonical-sql.cjs', code
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN hit;
END $$;

CREATE OR REPLACE FUNCTION canonical_voice_id(v text) RETURNS text
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE part text; out_parts text[] := '{}';
BEGIN
  v := btrim(coalesce(v, ''));
  IF v = '' OR lower(v) IN ('legacy_import','legacy','human','human_recording','unknown','default','auto') THEN
    RAISE EXCEPTION 'clip identity: voice_id % is a placeholder, not a voice', coalesce(v,'<null>')
      USING ERRCODE = 'check_violation';
  END IF;
  IF v ~* '^comp:' THEN
    FOREACH part IN ARRAY string_to_array(substr(v, 6), '+') LOOP
      IF btrim(part) <> '' THEN
        out_parts := out_parts || canonical_voice_id(btrim(part));
      END IF;
    END LOOP;
    IF array_length(out_parts, 1) IS NULL THEN
      RAISE EXCEPTION 'clip identity: composite voice_id % has no parts', v USING ERRCODE = 'check_violation';
    END IF;
    RETURN 'comp:' || array_to_string(out_parts, '+');
  END IF;
  IF v ~ '^(azure|xai|elevenlabs|google|narakeet|human)_.' THEN RETURN v; END IF;
  IF v ~ '^[a-z]{2,3}-[A-Za-z]{2,4}-[A-Za-z]+Neural$' THEN RETURN 'azure_' || v; END IF;
  IF lower(v) IN ('eve','leo','ara','sal','rex','gfzdpspr5fdp','bedd6226') THEN RETURN 'xai_' || v; END IF;
  RAISE EXCEPTION 'clip identity: voice_id % has no provider prefix and no inferable provider — the writer must supply one', v
    USING ERRCODE = 'check_violation';
END $$;

