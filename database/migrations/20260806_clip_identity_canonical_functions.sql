-- ── non-throwing variants, for audits and the back-fill ─────────────────────
CREATE OR REPLACE FUNCTION try_canonical_language(code text) RETURNS text
LANGUAGE plpgsql STABLE AS $$
BEGIN RETURN canonical_language(code); EXCEPTION WHEN OTHERS THEN RETURN NULL; END $$;

CREATE OR REPLACE FUNCTION try_canonical_voice_id(v text) RETURNS text
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN RETURN canonical_voice_id(v); EXCEPTION WHEN OTHERS THEN RETURN NULL; END $$;

