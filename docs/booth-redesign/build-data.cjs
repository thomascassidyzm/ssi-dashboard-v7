// Builds data.js for the three booth mockups from a saved copy of the live queue:
//   curl -s "https://popty.app/api/recording/voice/human_aran_cym_n?includeRecorded=1" -o q.json
//   node docs/booth-redesign/build-data.cjs q.json
// Design mockups only (job #335) — nothing here is read by the live booth.
const fs = require('fs'), path = require('path');
const q = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const L = q.lines;
const line = (l) => ({ cy: l.text, en: l.knownText || '', done: !!l.recorded, tag: l.phraseRole || (l.readStyle === 'gapped' ? 'with gaps' : '') });
const chunk = (a, n) => a.reduce((o, x, i) => (i % n ? o[o.length - 1].push(x) : o.push([x]), o), []);

const newSeeds = L.filter(l => l.kind === 'seed' && l.courseCode === 'cym_nv2_for_eng').sort((a, b) => a.seedNumber - b.seedNumber);
const seedBatches = chunk(newSeeds, 100).map((b, i) => ({
  n: i + 1, label: `Sentences ${b[0].seedNumber}–${b[b.length - 1].seedNumber}`,
  size: b.length, done: b.filter(l => l.recorded).length, lines: b.map(line),
}));

const P = q.phrases;
const ph = L.filter(l => l.kind === 'phrase');
const p1rest = P.passTotals[1] - P.batchLines, p1each = Math.round(p1rest / (P.batches - 1));
const p1 = Array.from({ length: P.batches }, (_, i) => i === 0
  ? { n: 1, label: `Sentences ${Math.min(...ph.map(l => l.seedNumber))}–${Math.max(...ph.map(l => l.seedNumber))}`, size: P.batchLines, done: P.batchRecorded, lines: ph.map(line) }
  : { n: i + 1, label: '', size: p1each, approx: true, done: 0, lines: null });
const p2each = Math.round(P.passTotals[2] / 16);
const p2 = Array.from({ length: 16 }, (_, i) => ({ n: i + 1, label: '', size: p2each, approx: true, done: 0, lines: null }));

const pod = (slug) => L.filter(l => l.kind === 'pod' && l.podSlug === slug);
const podTrack = (id, title, what, lines, extra = {}) => ({
  id, title, what, total: lines.length, done: lines.filter(l => l.recorded).length,
  batches: [{ n: 1, label: '', size: lines.filter(l => !l.recorded).length, done: 0, lines: lines.filter(l => !l.recorded).map(line) }], ...extra,
});
const oldSeeds = L.filter(l => l.kind === 'seed' && l.courseCode === 'cym_n_for_eng');

const data = {
  voice: q.displayName, fetched: new Date().toISOString().slice(0, 10),
  main: [
    { id: 'sent', title: 'New Welsh — whole sentences', short: 'Whole sentences', what: 'Read each new course sentence once, at your natural pace.',
      total: newSeeds.length, done: newSeeds.filter(l => l.recorded).length, batches: seedBatches },
    { id: 'p1', title: 'New Welsh — practice phrases, pass 1', short: 'Phrases · pass 1', what: 'The phrases the app plays first: up to 4 build and 3 use phrases for each new LEGO.',
      total: P.passTotals[1], done: P.passRecorded[1], batches: p1, oneAtATime: true },
    { id: 'p2', title: 'New Welsh — practice phrases, pass 2', short: 'Phrases · pass 2', what: 'The rest of the practice phrases. Opens when pass 1 is finished.',
      total: P.passTotals[2], done: P.passRecorded[2], batches: p2, locked: true },
  ],
  other: [
    podTrack('health', 'Health — ward and surgery', 'Your half of the health conversations.', pod('health')),
    podTrack('ladder', 'Health (test)', '5 lines, then the same 5 again with a pause at every mark.', [...pod('health-ladder-pilot'), ...L.filter(l => l.kind === 'takeg')]),
    podTrack('senedd', 'Senedd — S4C committee', 'The Senedd session, read in order.', pod('senedd-s4c-steve'), { waiting: 2 }),
  ],
  finished: [
    { title: 'Old Welsh — whole sentences', total: oldSeeds.length },
    { title: 'Welsh Pod 1', total: pod('pod-1').length },
    { title: 'I love you (guess games)', total: pod('guess-i-love-you').length },
  ],
};
fs.writeFileSync(path.join(__dirname, 'data.js'), '// generated by build-data.cjs from the live queue — real lines\nwindow.BOOTH = ' + JSON.stringify(data) + ';\n');
console.log(seedBatches.map(b => b.label + ' ' + b.size).join('\n'), '\np1 batch1', P.batchLines, 'others ~', p1each, 'p2 ~', p2each);
