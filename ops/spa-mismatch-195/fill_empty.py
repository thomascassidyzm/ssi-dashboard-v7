#!/usr/bin/env python3
"""spa_for_eng job #259 (copy of the deu #246 tool): list every non-component phrase with an EMPTY audio slot in a seeds dump
(argv[1] = GET /api/production/spa_for_eng/seeds) as #36-engine rows whose 'fix' is the row's CURRENT text on the
empty sides only, so `render` mode fills exactly those slots (library first, then one render) and touches nothing else.
Writes tools/course-optimization/spa-195-fill-empty-2026-11-04.data.cjs (every empty non-component slot in the course,
so a render run ends the course at 0 empty)."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
d = json.load(open(sys.argv[1])); fixes = []
for s in d['seeds']:
    for l in s['legos']:
        for p in l.get('basket_phrases') or []:
            if p.get('phrase_role') == 'component': continue
            k = None if p.get('known_audio_id') else p['known_text']
            t = None if (p.get('target1_audio_id') and p.get('target2_audio_id')) else p['target_text']
            if k or t: fixes.append([p['id'].split(':')[-1], 'fill', [p['known_text'], p['target_text']], [k, t], 'empty slot after #259 edits'])
# seeds too (job #259: seed 142's English changed, so its known slot is empty) — render mode reads SEED_FIXES the same way
seed_fixes = []
for s in d['seeds']:
    k = None if s.get('known_audio_id') else s['known_text']
    t = None if (s.get('target1_audio_id') and s.get('target2_audio_id')) else s['target_text']
    if k or t: seed_fixes.append([s['seed_number'], 'fill', [s['known_text'], s['target_text']], [k, t], 'empty seed slot after #259 edits'])
out = os.path.join(ROOT, 'tools/course-optimization/spa-195-fill-empty-2026-11-04.data.cjs')
with open(out, 'w') as f:
    f.write("'use strict';\n// GENERATED by ops/spa-mismatch-195/fill_empty.py (job #259) — `render` mode ONLY of the ita #36 engine.\n")
    f.write(f"const FIXES = {json.dumps(fixes, ensure_ascii=False, indent=1)};\nconst SEED_FIXES = {json.dumps(seed_fixes, ensure_ascii=False, indent=1)};\n")
    f.write("module.exports = { COURSE: 'spa_for_eng', LANGUAGE: 'Spanish', LOG_PREFIX: 'spa-195', JOB: '#259 fill',\n  AGENT: 'spa-mismatch-195 (job #259)', PURPOSE: 'job #259 spa_for_eng: fill the empty slots left from earlier passes so the course has 0 empty', FIXES, SEED_FIXES, LEGO_FIXES: [] };\n")
print(len(fixes), 'rows,', len(seed_fixes), 'seeds')
