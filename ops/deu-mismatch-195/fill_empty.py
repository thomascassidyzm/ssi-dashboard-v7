#!/usr/bin/env python3
"""deu_for_eng job #246 (copy of the fra #238 tool): list every non-component phrase with an EMPTY audio slot in a seeds dump
(argv[1] = GET /api/production/deu_for_eng/seeds) as #36-engine rows whose 'fix' is the row's CURRENT text on the
empty sides only, so `render` mode fills exactly those slots (library first, then one render) and touches nothing else.
Writes tools/course-optimization/deu-195-fill-empty-2026-11-04.data.cjs (every empty non-component slot in the course,
so a render run ends the course at 0 empty)."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
d = json.load(open(sys.argv[1])); fixes = []
for s in d['seeds']:
    for l in s['legos']:
        for p in l.get('basket_phrases') or []:
            if p.get('phrase_role') == 'component': continue
            k = None if p.get('known_audio_id') else p['known_text']
            t = None if (p.get('target1_audio_id') and p.get('target2_audio_id')) else p['target_text']
            if k or t: fixes.append([p['id'].split(':')[-1], 'fill', [p['known_text'], p['target_text']], [k, t], 'empty slot after #246 edits'])
out = os.path.join(ROOT, 'tools/course-optimization/deu-195-fill-empty-2026-11-04.data.cjs')
with open(out, 'w') as f:
    f.write("'use strict';\n// GENERATED by ops/deu-mismatch-195/fill_empty.py (job #246) — `render` mode ONLY of the ita #36 engine.\n")
    f.write(f"const FIXES = {json.dumps(fixes, ensure_ascii=False, indent=1)};\n")
    f.write("module.exports = { COURSE: 'deu_for_eng', LANGUAGE: 'German', LOG_PREFIX: 'deu-195', JOB: '#246 fill',\n  AGENT: 'deu-mismatch-195 (job #246)', PURPOSE: 'job #246 deu_for_eng: fill the empty slots left from earlier passes so the course has 0 empty', FIXES, SEED_FIXES: [], LEGO_FIXES: [] };\n")
print(len(fixes), 'rows')
