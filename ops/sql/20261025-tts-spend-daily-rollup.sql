CREATE TABLE public.tts_spend_daily (
  provider text NOT NULL,
  day      date NOT NULL,
  kind     text NOT NULL,
  chars    bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (provider, day, kind)
);
-- No secondary index (adversary round 2): every reserve updates one
-- (provider, day, 'call') row, and an index carrying chars would make each of
-- those updates non-HOT; the table holds ~100 rows, one page.
CREATE TABLE public.tts_spend_daily_job (
  day   date NOT NULL,
  job   text NOT NULL,
  chars bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (day, job)
);
