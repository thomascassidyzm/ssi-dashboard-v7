-- THE TTS SPEND GUARD READS A PER-DAY ROLLUP, NOT THE LEDGER (job #806, R1b,
-- brought into round 1 on the adversary's evidence, #828·P).
--
-- WHY. Every reserve (227k calls, mean 201 ms, 17% of all DB time since
-- 2026-09-26) and every totals call (985k) summed raw ledger rows: today's for
-- the caps, and MONTH-TO-DATE per provider for the cycle stop. At 68-79k rows a
-- day that sum grows all month, ~1.5M rows by 31 October and ~350 ms a call even
-- index-only, under the two global advisory locks every render queues behind.
-- v_approved_all also ran a regex per ledger row (151 ms warm).
--
-- WHAT. Two rollups kept by an AFTER INSERT trigger on tts_spend_ledger, so
-- every writer (tts_spend_insert, and anything inserting directly) is covered:
--   tts_spend_daily      (provider, day, kind) -> chars     every row
--   tts_spend_daily_job  (day, job)            -> chars     kind = 'call', job not null
-- The columns it sums are immutable by trigger (id, at, kind, provider, chars;
-- tts_spend_ledger_immutable) and rows are never deleted or truncated, so an
-- insert-only rollup is exact. job is not in the immutable list, but nothing
-- updates it (tts_spend_settle writes status/settled_at/note only).
-- day = (at AT TIME ZONE 'UTC')::date; v_day and tts_spend_cycle_start are UTC
-- midnights, so "at >= v_day" equals "day >= v_day::date", future-dated rows
-- included either way. The approval regex now runs over today's distinct jobs.
-- tts_spend_reserve and tts_spend_totals change ONLY those six sums; every cap,
-- lock, message and order is the live text, byte for byte (generated by
-- ops/db-10x/r1-test/gen-rollup.py from pg_get_functiondef).
-- The ledger stays the truth: tts_spend_rollup_drift() names any
-- (provider, day, kind) or (day, job) where rollup and ledger disagree.
--
-- APPLY. One transaction. LOCK TABLE tts_spend_ledger IN SHARE MODE holds
-- inserts (renders wait, reads carry on) for the backfill (154 ms warm), so no
-- row can land between the trigger and the backfill. A reserve stalled behind
-- it past PostgREST's 8 s lock_timeout would fail as "ledger unreachable", so
-- ops/db-10x/apply.sh warms the ledger into cache first and runs this file
-- with transaction_timeout = 6s: it commits fast or aborts, never stalls.
-- Direct psql as postgres; lock_timeout 5s.
--
-- Rollback: 20261025e_tts_spend_daily_rollup.rollback.sql (restores the live
-- function text from before this migration, then drops trigger and rollups).
-- ============================================================================
